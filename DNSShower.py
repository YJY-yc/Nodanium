def flush_dns_cache():
    """跨平台刷新DNS缓存"""
    if sys_type == "Windows":
        ProcUtil.run(['ipconfig', '/flushdns'], capture_output=True)
    elif sys_type == "Linux":
  
        attempts = [
            ['resolvectl', 'flush-caches'],
            ['systemd-resolve', '--flush-caches'],
            ['resolvconf', '-u'],
        ]
        done = False
        for cmd in attempts:
            try:
                r = ProcUtil.run(cmd, capture_output=True)
                if r.returncode == 0:
                    done = True
                    break
            except FileNotFoundError:
                continue
        if not done:
            try:
                ProcUtil.run(['nscd', '-i', 'hosts'], capture_output=True)
            except FileNotFoundError:
                pass

module_flush_dns_cache = flush_dns_cache


def resolve_dns(domain: str, record_types=("A", "AAAA", "CNAME", "MX", "TXT")) -> dict:
    domain = (domain or "").strip()
    if not domain:
        raise ValueError("域名不能为空")
    result = {}
    resolver = dns.resolver.Resolver()
    resolver.lifetime = 5.0
    resolver.timeout = 5.0
    for rtype in record_types:
        try:
            answers = resolver.resolve(domain, rtype)
            result[rtype] = [str(r) for r in answers]
        except Exception:
            result[rtype] = []
    if not any(result.values()):
        raise ValueError("未能解析出任何 DNS 记录: %s" % domain)
    return result


