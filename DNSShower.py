# ===== hosts 内容读写与校验 =====
HOSTNAME_RE = re.compile(r'^(?!-)[A-Za-z0-9_-]{1,63}(?<!-)(\.(?!-)[A-Za-z0-9_-]{1,63}(?<!-))*\.?$')

def hosts_line_for(ip: str, hostname: str) -> str:
    return "%s\t%s" % (ip, hostname)

def validate_hosts_entry(ip: str, hostname: str) -> str:
    try:
        ipaddress.ip_address(ip)
    except ValueError:
        raise ValueError("IP 地址格式不正确: %s" % ip)
    if not HOSTNAME_RE.match(hostname):
        raise ValueError("主机名格式不正确: %s" % hostname)
    return hosts_line_for(ip, hostname)

def resolve_hosts_path() -> str:
    if sys_type != "Windows":
        return HOSTS_PATH
    win_dir = os.environ.get("SystemRoot") or os.environ.get("windir") or r"C:\Windows"
    return os.path.join(win_dir, "System32", "drivers", "etc", "hosts")


def read_hosts_text() -> str:
    for path in (HOSTS_PATH, resolve_hosts_path()):
        try:
            with open(path, "r", encoding="utf-8", errors="replace", newline="") as f:
                return f.read()
        except FileNotFoundError:
            continue
        except PermissionError:
            raise
    return ""


def detect_newline(text: str) -> str:
    return "\r\n" if "\r\n" in text else "\n"


def needs_final_newline(text: str) -> bool:
    return bool(text) and not text.endswith(("\n", "\r"))

def hostname_ip_map(text: str) -> dict:
    result = {}
    for raw in text.splitlines():
        line = raw.split('#', 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) < 2:
            continue
        ip = parts[0]
        for name in parts[1:]:
            result.setdefault(name.lower(), []).append(ip)
    return result

def add_hosts_entry(ip: str, hostname: str) -> bool:
    line = validate_hosts_entry(ip, hostname)
    text = read_hosts_text()
    existing = hostname_ip_map(text).get(hostname.lower())
    if existing and ip in existing:
        return False
    nl = detect_newline(text)
    if needs_final_newline(text):
        text += nl
    text += line + nl
    write_hosts_with_privileges(text)
    return True


def remove_hosts_entry(hostname: str, ip: str) -> bool:
    text = read_hosts_text()
    nl = detect_newline(text)
    new_lines = []
    removed = False
    for raw in text.splitlines():
        stripped = raw.strip()
        if stripped and not stripped.startswith('#'):
            parts = stripped.split('#', 1)[0].split()
            if len(parts) >= 2 and parts[0] == ip and hostname in parts[1:]:
                removed = True
                continue
        new_lines.append(raw)
    if not removed:
        return False
    content = nl.join(new_lines)
    if content and not content.endswith(nl):
        content += nl
    write_hosts_with_privileges(content)
    return True

# ===== 标准 Linux hosts 默认模板 =====
def generate_linux_default_hosts(hostname: str = "") -> str:
    """生成标准 Linux 默认 hosts 文件内容（含 localhost、主机名、IPv6 条目）"""
    if not hostname:
        try:
            hostname = socket.gethostname()
        except Exception:
            hostname = "localhost"
    hostname = hostname.split(".")[0].strip() or "localhost"
    return (
        "# Hosts file generated by Nodanium\r\n"
        "# /etc/hosts - local name resolution database\r\n"
        "\r\n"
        "127.0.0.1\tlocalhost\r\n"
        f"127.0.1.1\t{hostname}\r\n"
        "\r\n"
        "# The following lines are desirable for IPv6 capable hosts\r\n"
        "::1\t\tip6-localhost ip6-loopback\r\n"
        "fe00::\t\tip6-localnet\r\n"
        "ff00::\t\tip6-mcastprefix\r\n"
        "ff02::1\t\tip6-allnodes\r\n"
        "ff02::2\t\tip6-allrouters\r\n"
        "\r\n"
    )


def generate_windows_default_hosts() -> str:
    from host import host as _host_template
    text = _host_template.replace("\r\n", "\n").replace("\r", "\n")
    if not text.endswith("\n"):
        text += "\n"
    return text.replace("\n", "\r\n")


def write_hosts_with_privileges(content: str) -> None:

    data = content.encode("utf-8")

    for path in (HOSTS_PATH, resolve_hosts_path()):
        if not os.path.exists(path):
            continue
        try:
            with open(path, "r+b") as f:
                f.seek(0)
                f.write(data)
                f.truncate()
            return
        except PermissionError:
            pass
        except OSError:
            pass

    if sys_type == "Windows":
        raise PermissionError(
            "无法写入 hosts 文件 %s，请以管理员身份重新启动 Nodanium" % resolve_hosts_path()
        )

    os.makedirs(os.path.dirname(HOSTS_PATH), exist_ok=True)
    tmp_file = HOSTS_PATH + ".nodanium.tmp"
    try:
        with open(tmp_file, "wb") as f:
            f.write(data)
    except OSError as e:
        raise PermissionError("无法创建临时文件 %s: %s" % (tmp_file, e))


    shell_cmd = "cat '%s' > '%s' && rm -f '%s'" % (tmp_file, HOSTS_PATH, tmp_file)
    for tool in ("pkexec", "sudo", "su"):
        if tool == "pkexec":
            candidate = ["pkexec", "sh", "-c", shell_cmd]
        elif tool == "sudo":
            candidate = ["sudo", "-n", "sh", "-c", shell_cmd]
        else:
            candidate = ["su", "-c", shell_cmd]
        try:
            result = ProcUtil.run(
                candidate,
                capture_output=True,
                text=True,
                timeout=120,
            )
            if result.returncode == 0:
                try:
                    if os.path.exists(tmp_file):
                        os.remove(tmp_file)
                except OSError:
                    pass
                return
        except FileNotFoundError:
            continue
        except Exception:
            continue


    try:
        if os.path.exists(tmp_file):
            os.remove(tmp_file)
    except Exception:
        pass
    raise PermissionError("无法获得写 /etc/hosts 的权限（尝试了 pkexec/sudo 仍失败）")


